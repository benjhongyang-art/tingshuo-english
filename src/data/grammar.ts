const byTopic = new Map<string, GrammarQuestion[]>()
for (const question of grammarQuestions) {
  const list = byTopic.get(question.topicId) ?? []
  list.push(question)
  byTopic.set(question.topicId, list)
}

export function getGrammarTopic(id: string | undefined): GrammarTopic | undefined {
  return grammarTopics.find((topic) => topic.id === id)
}

export function questionsFor(topicId: string): GrammarQuestion[] {
  return byTopic.get(topicId) ?? []
}
