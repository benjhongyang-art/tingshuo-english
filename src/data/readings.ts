const byId = new Map(readings.map((passage) => [passage.id, passage]))

export function getReading(id: string | undefined): ReadingPassage | undefined {
  return id ? byId.get(id) : undefined
}

export function readingsFor(level: ReadingLevel | "all"): ReadingPassage[] {
  if (level === "all") return readings
  return readings.filter((passage) => passage.level === level)
}
